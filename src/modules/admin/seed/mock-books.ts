// Обложка: переиспользуем документ media с тем же файлом (включая Payload-копии с суффиксом
// «-1» — потому ищем по базовому имени), иначе создаём из файла на диске; если файла нет —
// предупреждение и книга без обложки, а не падение сева.
async function resolveCover(payload: Payload, coverFile: string, alt: string): Promise<number | null> {
    const stem = coverFile.replace(/\.[^.]+$/, '')

    const existing = await payload.find({
        collection: 'media',
        where: { filename: { like: stem } },
        limit: 1,
    })

    if (existing.docs.length > 0) {
        return existing.docs[0].id
    }

    try {
        const media = await payload.create({
            collection: 'media',
            data: { alt },
            filePath: path.resolve(MEDIA_DIR, coverFile),
        })

        return media.id
    } catch {
        payload.logger.warn(`Обложка «${coverFile}» не найдена в media/ — книга будет без обложки`)
        return null
    }
}

// Вызывается в onInit: сеет книги только в пустую коллекцию, чтобы перезапуски не плодили дубли.
export async function seedMockBooks(payload: Payload): Promise<void> {
    const { totalDocs } = await payload.count({ collection: 'books' })

    if (totalDocs > 0) {
        return
    }

    for (const mock of MOCK_BOOKS) {
        const { coverFile, notes, ...data } = mock
        const cover = coverFile !== undefined ? await resolveCover(payload, coverFile, mock.title) : null

        const book = await payload.create({
            collection: 'books',
            data: cover !== null ? { ...data, cover } : data,
        })

        for (const note of notes ?? []) {
            await payload.create({
                collection: 'notes',
                data: { title: note.title, book: book.id, content: note.content },
            })
        }
    }

    payload.logger.info(`Занесено моковых книг: ${MOCK_BOOKS.length}`)
}
